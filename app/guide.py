NEW = [x[0] for _, items in RELEASES for x in items]          # 全部（舊的說明書頁、相容用）
NEW_NOW = [x[0] for x in RELEASES[0][1]]                       # 這一版新增的
KEY = 'guide:' + VERSION

def managers(con):
    """要看說明書的人：中控台管理層帳號（管理員、客服排班、帳務），不含本機管理員。"""
    return c.rows(con, "SELECT id,name,role,last_login FROM users WHERE active=1 AND role IN ('admin','staff','finance') AND id!='u-local' ORDER BY created_at")

def seen(con, uid):
    return bool(con.execute('SELECT 1 FROM tours WHERE user_id=? AND key=?', (uid, KEY)).fetchone())

def state(con, user):
    out = {'version': VERSION, 'new': NEW_NOW, 'key': KEY,
           'releases': [{'v': v, 'items': [dict(zip(('t', 'go', 'sel', 'prep', 'how'), x)) for x in items]} for v, items in RELEASES]}
    if user['role'] == 'admin':
        out['status'] = [{'name': u['name'], 'seen': seen(con, u['id']), 'last_login': (u['last_login'] or '')[:16].replace('T', ' ')} for u in managers(con)]
    return out

def remind(con):
    """新版說明書上線 → 派單管理群 @管理層「請登入後台看一遍」（從沒登入過、有綁 LINE 的人另外一對一傳登入連結）；
    之後每天 10:30 列出還沒看完的人，全部看完就停。08:00–22:00 才發。"""
    import line_bot as lb
    now = dt.datetime.now(c.TZ)
    if not ('08:00' <= now.strftime('%H:%M') < '22:00'):
        return 0
    pending = [u for u in managers(con) if not seen(con, u['id'])]
    first = ix.setting(con, 'guide_announced') != VERSION
    if not pending:
        if first:
            ix.set_setting(con, 'guide_announced', VERSION)
        return 0
    if not first and (now.strftime('%H:%M') < '10:30' or ix.setting(con, 'guide_remind_day') == now.date().isoformat()):
        return 0
    ix.set_setting(con, 'guide_announced', VERSION); ix.set_setting(con, 'guide_remind_day', now.date().isoformat())
    names = '、'.join(u['name'] for u in pending)
    tip = (f'📘 中控台有新功能（{VERSION}）。請管理層登入後台，會自動跳出這次的「新功能導覽」（只看新的，約 1–2 分鐘），看完系統會自動記錄。'
           if first else f'📘 中控台新功能（{VERSION}）還沒看：{names}。請登入後台，會自動跳出新功能導覽（或按右上角「?」→「新功能導覽」）。')
    rows = [lb._t(f'・{x}', wrap=True, size='sm') for x in NEW_NOW[:8]] + [{'type': 'separator', 'margin': 'lg', 'color': lb.LINE_C}, lb._row('還沒看完', names)]
    card = lb.flex(f'中控台新功能導覽（{VERSION}）', lb._bubble(lb._header('新功能導覽 📘', f'{VERSION} 更新', '#0A84FF'), rows,
                   [lb._btn('打開中控台看新功能', uri=f'{lb.BASE_URL}/#home', primary=True)], '登入就會跳出新功能導覽；每一頁怎麼用按右上角「?」。'))
    g = lb.admin_group(con)
    if g and ix.setting(con, 'standing_push') == 'on':      # 省額度 → 新功能導覽不另外推，10:30 那一則寫「誰還沒看」（登入中控台會自動跳出）
        lb.queue(con, lb.WORK_ACCOUNT, g, 'guide_new', card[0]['altText'], [lb.ping(con, tip, who=sorted(lb.staff_users(con)))] + card)
    if first:                     # 從沒登入過後台的人（例：店長）：一對一傳一次性登入連結
        ids = {u['id'] for u in pending if not u['last_login']}
        for k, v in con.execute("SELECT key,value FROM settings WHERE key LIKE 'login_user:%'").fetchall():
            if v in ids and ix.setting(con, f'magic_day:{v}') != now.date().isoformat():      # 一天最多一次（同一天改版好幾次不要一直傳）
                ix.set_setting(con, f'magic_day:{v}', now.date().isoformat())
                lb.queue(con, lb.WORK_ACCOUNT, k.split(':', 1)[1], 'magic', '中控台登入連結', lb.card_magic(con, v, 24))
    return len(pending)
