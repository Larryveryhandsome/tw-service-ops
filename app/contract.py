def digest(t):
    """條款內容雜湊：簽約時一起存，之後改條款也能證明當時同意的是哪一版。"""
    return hashlib.sha256(json.dumps(t, ensure_ascii=False, sort_keys=True).encode()).hexdigest()[:16]
